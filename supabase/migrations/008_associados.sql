-- ---------- Tabelas ---------------------------------------------------

-- Um pedido por submissão do formulário "Pedido de adesão" no Tally.
create table public.pedidos_adesao (
  id                        uuid primary key default gen_random_uuid(),
  tally_id                  text not null unique,                 -- responseId do Tally
  data_pedido               timestamptz not null,                 -- data de submissão no Tally
  nome_completo             text not null check (length(trim(nome_completo)) > 0),
  nome_emails               text not null check (length(trim(nome_emails)) > 0),
  email                     citext not null,
  -- 'dd/mm', sem ano; facultativo. Preenchido = consentimento para o email 12.
  aniversario               text
                            check (aniversario is null or (
                              aniversario ~ '^(0[1-9]|[12][0-9]|3[01])/(0[1-9]|1[0-2])$'
                              and aniversario not in ('30/02', '31/02', '31/04', '31/06', '31/09', '31/11'))),
  primeiro_contacto         text,
  newsletter                boolean not null default false,
  consentimento             boolean not null default false,
  estado                    text not null default 'recebido'
                            check (estado in ('recebido', 'instrucoes_enviadas', 'pago', 'admitido',
                                              'desistiu', 'nao_admitido', 'cancelado')),
  data_pagamento            date,
  pagamento_confirmado_por  uuid references public.perfis(id) on delete set null,
  contacto_id               uuid references public.contactos(id) on delete set null,
  notas                     text,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now(),  -- actualizado por quem grava
  check (estado not in ('pago', 'admitido') or data_pagamento is not null)
);

-- Uma linha por associado admitido.
create table public.associados (
  id             uuid primary key default gen_random_uuid(),
  -- restrict: um contacto que é associado não se apaga no Rede (SPEC 16.6)
  contacto_id    uuid not null unique references public.contactos(id) on delete restrict,
  pedido_id      uuid unique references public.pedidos_adesao(id) on delete set null,
  numero         integer not null unique generated by default as identity (start with 1),
  tipo           text not null default 'efectivo' check (tipo in ('efectivo', 'aderente')),
  fundador       boolean not null default false,
  data_admissao  date not null default current_date,
  admitido_por   uuid references public.perfis(id) on delete set null,
  estado         text not null default 'activo' check (estado in ('activo', 'suspenso', 'saido')),
  created_at     timestamptz not null default now()
);

-- Uma quota por associado e ano.
create table public.quotas (
  id              uuid primary key default gen_random_uuid(),
  associado_id    uuid not null references public.associados(id) on delete restrict,
  ano             integer not null check (ano between 2026 and 2100),
  valor           numeric(8, 2) not null check (valor >= 0),
  estado          text not null default 'nao_paga' check (estado in ('paga', 'nao_paga')),
  data_pagamento  date,
  recibo_numero   text,
  recibo_data     date,
  created_at      timestamptz not null default now(),
  unique (associado_id, ano),
  check ((estado = 'paga') = (data_pagamento is not null)),
  check (recibo_data is null or recibo_numero is not null)
);

-- Os textos dos emails-tipo, editáveis no admin.
create table public.emails_tipo (
  chave       text primary key check (chave ~ '^[0-9]{2}[a-z]?_[a-z0-9_]+$'),
  nome        text not null,
  quando      text,                                   -- a linha "Quando · Envio" do documento
  assunto     text not null,
  corpo       text not null,
  automatico  boolean not null,
  activo      boolean not null default true,
  updated_at  timestamptz not null default now()
);

-- Registo de cada envio (e de cada tentativa falhada).
create table public.emails_enviados (
  id                 uuid primary key default gen_random_uuid(),
  email_tipo         text not null references public.emails_tipo(chave) on update cascade,
  pedido_id          uuid references public.pedidos_adesao(id) on delete cascade,
  associado_id       uuid references public.associados(id) on delete restrict,
  -- '' nos emails únicos; 'AAAA' nos anuais (12, 13, 16); 'AAAA-Tn' no 17
  periodo            text not null default '' check (periodo ~ '^([0-9]{4}(-T[1-4])?)?$'),
  destinatario       citext not null,
  assunto            text not null,
  corpo              text,
  enviado_em         timestamptz not null default now(),
  estado             text not null default 'a_enviar' check (estado in ('a_enviar', 'enviado', 'falhou')),
  resposta_provider  text,
  check ((pedido_id is null) <> (associado_id is null))
);

-- Valores usados nos emails, editáveis no admin.
create table public.configuracao (
  chave       text primary key,
  valor       text,
  descricao   text,
  updated_at  timestamptz not null default now()
);

-- ---------- Índices --------------------------------------------------

-- Nunca o mesmo email-tipo duas vezes ao mesmo pedido/associado no mesmo período.
-- As tentativas falhadas não contam (tenta-se de novo); as reservas (a_enviar) contam.
create unique index emails_enviados_unico
  on public.emails_enviados (email_tipo, pedido_id, associado_id, periodo)
  nulls not distinct
  where estado <> 'falhou';

create index pedidos_adesao_email_idx      on public.pedidos_adesao (email);
create index pedidos_adesao_estado_idx     on public.pedidos_adesao (estado);
create index pedidos_adesao_contacto_idx   on public.pedidos_adesao (contacto_id);
create index associados_estado_idx         on public.associados (estado);
create index quotas_ano_estado_idx         on public.quotas (ano, estado);
create index emails_enviados_pedido_idx    on public.emails_enviados (pedido_id);
create index emails_enviados_associado_idx on public.emails_enviados (associado_id);
create index emails_enviados_data_idx      on public.emails_enviados (enviado_em desc);

